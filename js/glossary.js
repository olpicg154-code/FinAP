function renderGlossary(data) {

    const container =
        document.getElementById("glossaryTerms");

    if (!container) return;

    container.innerHTML = "";

    data.forEach((item, index) => {

        const card = document.createElement("div");

        card.className = "glossary-term";

        card.innerHTML = `
            <div class="term-name">${item.term}</div>
            <div class="term-full">${item.full}</div>
        `;

        card.addEventListener("click", () => {

            document
                .querySelectorAll(".glossary-term")
                .forEach(el =>
                    el.classList.remove("active")
                );

            card.classList.add("active");

            showDefinition(item);
        });

        container.appendChild(card);

        if (index === 0) {
            setTimeout(() => card.click(), 0);
        }
    });
}


function showDefinition(item) {

    const definition =
        document.getElementById("glossaryDefinition");

    if (!definition) return;

    definition.innerHTML = `
        <h3 class="definition-title">
            ${item.term}
        </h3>

        <div class="definition-full">
            ${item.full}
        </div>

        <div class="definition-text">
            ${item.text}
        </div>
    `;
}


function initGlossary() {

    const search =
        document.getElementById("glossarySearch");

    if (!search) return;

    renderGlossary(glossaryData);

    search.addEventListener("input", () => {

        const query =
            search.value.trim().toLowerCase();

        const filtered =
            glossaryData.filter(item =>
                item.term.toLowerCase().includes(query) ||
                item.full.toLowerCase().includes(query) ||
                item.text.toLowerCase().includes(query)
            );

        renderGlossary(filtered);
    });
}


